#!/bin/sh
# Writes /data/nginx/custom/sso/npm.js inside the proxy manager: a script that
# gives browsers that passed the Authelia gate a 30-day admin token for the
# proxy manager's web UI, so it opens without its own login.
# The token is signed with the proxy manager's own key and is never stored in git.
# Run weekly by npm-sso-token.timer.
set -eu
CONTAINER=${NPM_CONTAINER:-nginx}

docker exec -i -w /app "$CONTAINER" node --input-type=module <<'JS'
import fs from "node:fs";
const cfg = await import("/app/lib/config.js");
if (cfg.configure) await cfg.configure();
const Token = (await import("/app/models/token.js")).default;
const days = 30;
const { token } = await Token().create({ iss: "api", attrs: { id: 1 }, scope: ["user"], expiresIn: `${days}d` });
const expires = new Date(Date.now() + days * 864e5).toISOString();
const js = `// Generated by sso/npm/mint-token.sh. Do not commit.
(function () {
  try {
    var key = "authentications", now = Date.now();
    var saved = JSON.parse(localStorage.getItem(key) || "[]");
    var valid = saved.some(function (t) { return t && t.token && new Date(t.expires).getTime() > now; });
    if (!valid) localStorage.setItem(key, JSON.stringify([{ token: ${JSON.stringify(token)}, expires: ${JSON.stringify(expires)} }]));
  } catch (e) {}
})();
`;
fs.mkdirSync("/data/nginx/custom/sso", { recursive: true });
fs.writeFileSync("/data/nginx/custom/sso/npm.js", js, { mode: 0o644 });
console.log("npm.js written, valid until " + expires);
JS
