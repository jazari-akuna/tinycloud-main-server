#!/usr/bin/env python3
"""Builds configuration.yml from configuration.template.yml and ../apps.yml.

Each app in apps.yml gets an access rule: administrators can always open it, and
people given the app on the people page (group app-<key>) can too, unless the
app is for administrators only. Apps that sign in with OpenID get a matching
OpenID policy of the same name. Run it after changing apps.yml or the template.
"""
import os
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))


def subject(app):
    if app["access"] == "admins":
        return ["group:admins"]
    return [["group:admins"], ["group:app-%s" % app["key"]]]


def main():
    apps = yaml.safe_load(open(os.path.join(HERE, "..", "apps.yml")))["apps"]
    rules, policies = [], {}
    for app in apps:
        if app["access"] == "open":
            continue
        rule = {"domain": app["domains"]}
        if app.get("paths"):
            rule["resources"] = app["paths"]
        rule["subject"] = subject(app)
        rule["policy"] = "one_factor"
        rules.append(rule)
        if app.get("paths"):  # the rest of the site stays public
            rules.append({"domain": list(app["domains"]), "policy": "bypass"})
        if app.get("sign_in") == "openid":
            policies[app["key"]] = {"default_policy": "deny",
                                    "rules": [{"policy": "one_factor", "subject": s} for s in
                                              (subject(app) if app["access"] != "admins" else [["group:admins"]])]}

    def block(obj, indent):
        text = yaml.safe_dump(obj, default_flow_style=None, sort_keys=False, width=200)
        return "\n".join(" " * indent + line for line in text.rstrip().split("\n"))

    tpl = open(os.path.join(HERE, "configuration.template.yml")).read()
    out = []
    for line in tpl.split("\n"):
        if "# @APP_RULES@" in line:
            out.append("    # Generated from ../apps.yml by render.py: do not edit here.")
            out.append(block(rules, 4))
        elif "# @OIDC_POLICIES@" in line:
            out.append("    # Generated from ../apps.yml by render.py: do not edit here.")
            out.append(block({"authorization_policies": policies}, 4))
        elif line.startswith("# Template:"):
            out.append("# Generated by render.py from configuration.template.yml and ../apps.yml. Edit those, not this file.")
        else:
            out.append(line)
    open(os.path.join(HERE, "configuration.yml"), "w").write("\n".join(out))
    print("configuration.yml: %d access rules, %d OpenID policies" % (len(rules), len(policies)))


if __name__ == "__main__":
    sys.exit(main())
